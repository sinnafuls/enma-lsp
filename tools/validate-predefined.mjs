// §A9 CI parser-validation gate.
// Run via: npm run validate-predefined
//
// 1. Runs regenerate-stdlib.mjs to ensure the predefined file is up-to-date.
// 2. Pipes enma-stdlib.em.predefined through tokenize + preprocess + parse via
//    ts-node (available as a devDependency in server/).
// 3. Exits 1 if any diagnostic is emitted; exits 0 on clean parse.

import { execSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');
const serverDir = path.join(repoRoot, 'server');

// ---- Step 1: regenerate -------------------------------------------------------

console.log('validate-predefined: regenerating stdlib...');
try {
    execSync('node tools/regenerate-stdlib.mjs', {
        cwd: repoRoot,
        stdio: 'inherit',
    });
} catch {
    console.error('validate-predefined: regenerate-stdlib failed');
    process.exit(1);
}

// ---- Step 2: build validation runner TS file inside server/test/ --------------

const predefinedPath = path.join(
    repoRoot, 'server', 'src', 'predefined', 'enma-stdlib.em.predefined'
).replace(/\\/g, '/');

if (!fs.existsSync(predefinedPath)) {
    console.error(`validate-predefined: ERROR — ${predefinedPath} not found after regeneration`);
    process.exit(1);
}

// Place the runner inside server/ so it can resolve relative to server/src/
const tmpDir = path.join(serverDir, '.tmp-validate');
fs.mkdirSync(tmpDir, { recursive: true });
const runnerPath = path.join(tmpDir, 'runner.ts');

// Imports are relative to server/.tmp-validate/ → server/src/ is one level up
const tsContent = `\
// Auto-generated by validate-predefined.mjs — do not edit.
process.env['ENMA_LSP_TEST'] = '1';

import { tokenize } from '../src/compiler_tokenizer/tokenizer';
import { preprocessAfterTokenized } from '../src/compiler_parser/parserPreprocess';
import { parseAfterPreprocessed } from '../src/compiler_parser/parser';
import * as fs from 'node:fs';

const src = fs.readFileSync(${JSON.stringify(predefinedPath)}, 'utf8');
const uri = 'file:///enma-stdlib.em.predefined';

const tokens = tokenize(uri, src);
const pre = preprocessAfterTokenized(tokens, { fileUri: uri });
const parsed = parseAfterPreprocessed(pre, { fileUri: uri });
const allDiags = [...pre.diagnostics, ...parsed.diagnostics];
if (allDiags.length > 0) {
    console.error('validate-predefined: FAILED — ' + allDiags.length + ' diagnostic(s)');
    for (const d of allDiags) {
        const line = d.location.start.line + 1;
        const col = d.location.start.character + 1;
        console.error('  ' + d.severity + ' ' + line + ':' + col + ': ' + d.message);
    }
    process.exit(1);
}
const loc = src.split('\\n').length;
console.log('validate-predefined: OK — 0 diagnostics, ' + loc + ' LoC');
`;

fs.writeFileSync(runnerPath, tsContent, 'utf8');

// ---- Step 3: run via server's ts-node using server's tsconfig -----------------

console.log('validate-predefined: running parser validation...');

// ts-node is installed in server/node_modules
const tsnodeBin = path.join(serverDir, 'node_modules', '.bin', 'ts-node');
const tsnodeCmd = fs.existsSync(tsnodeBin)
    ? `"${tsnodeBin.replace(/\\/g, '/')}"`
    : 'npx ts-node';

// Use server's tsconfig so all server source paths resolve correctly.
// We use --skipProject to avoid composite/incremental constraints, and
// pass the needed compilerOptions inline.
const compilerOpts = JSON.stringify(JSON.stringify({
    module: 'commonjs',
    target: 'ES2020',
    esModuleInterop: true,
    strict: false,
    skipLibCheck: true,
}));

try {
    execSync(
        `${tsnodeCmd} --skip-project --compiler-options ${compilerOpts} "${runnerPath.replace(/\\/g, '/')}"`,
        { cwd: serverDir, stdio: 'inherit' }
    );
} catch {
    try { fs.rmSync(tmpDir, { recursive: true, force: true }); } catch { /* ignore */ }
    process.exit(1);
}

// Cleanup temp files
try { fs.rmSync(tmpDir, { recursive: true, force: true }); } catch { /* ignore */ }

// ---- Step 4: assert example/perception.em.predefined matches canonical -------
// Strips leading // comment lines from the example copy before comparing,
// to allow the "COPY of ..." header comment without failing the check.

console.log('validate-predefined: checking example/perception.em.predefined matches canonical...');

const canonicalPath = path.join(repoRoot, 'server', 'src', 'predefined', 'perception.em.predefined');
const examplePath   = path.join(repoRoot, 'example', 'perception.em.predefined');

if (!fs.existsSync(examplePath)) {
    console.log('validate-predefined: example/perception.em.predefined not found — skipping drift check.');
} else {
    const canonical = fs.readFileSync(canonicalPath, 'utf8');
    const exampleRaw = fs.readFileSync(examplePath, 'utf8');
    // Strip leading comment lines added as copy-notice headers
    const stripLeadingComments = (s) => s.replace(/^(\/\/[^\n]*\n)+/, '');
    const canonicalStripped = stripLeadingComments(canonical);
    const exampleStripped   = stripLeadingComments(exampleRaw);
    if (canonicalStripped !== exampleStripped) {
        console.error('validate-predefined: DRIFT DETECTED — example/perception.em.predefined differs from server/src/predefined/perception.em.predefined');
        console.error('  Update example/perception.em.predefined by copying from the canonical source.');
        process.exit(1);
    }
    console.log('validate-predefined: OK — example/perception.em.predefined matches canonical.');
}
